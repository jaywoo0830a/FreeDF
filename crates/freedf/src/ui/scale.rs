//! Sizing scale — 모든 UI 치수를 여기 규약(helper/token)으로만 찍도록 강제합니다.
//!
//! # 치수 규약 (Size Rule)
//! 기반 단위 **1rem = 16px**. 치수는 반드시 아래 계층 중 하나로 표현한다.
//!
//! | 계층 | 계단 | 규칙 | 용도 |
//! |------|------|------|------|
//! | 소형 `qrem(n)` | 4px (0.25rem) | n×4 | gap / padding / inset |
//! | **중형 모듈러 토큰** | **×1.5 (0.25rem 스냅)** | **S_12 → S_16 → S_24 → S_36 → S_52 → S_80 → S_120 → S_180 → S_272 → S_408** | **컨트롤 높이·폭 등 표준 규격** |
//! | 대형 `rem(n)` | 16px (1rem) | n×16 | 창 / 패널 / 오버레이 크기 |
//!
//! **모듈러 규약**: 중형 정거장은 0.75rem에서 시작하는 **×1.5 지수 스케일**을
//! 0.25rem 계단으로 스냅한 값만 사용 — 모든 토큰은 rem으로 정의된다.
//! 정거장 사이의 임의 값(26/30/32 같은)은 금지.
//!
//! ```ignore
//! let w = crate::ui::scale::rem(44);    // 704px — 대형 (1rem 계단)
//! let h = crate::ui::scale::S_36;       // 36px (2.25rem) — 표준 버튼 높이
//! let g = crate::ui::scale::qrem(2);    //  8px — 소형 (0.25rem 계단)
//! ```

#![allow(dead_code)] // 상수/유틸은 필요 시 호출자가 재사용 (선재 위치).

/// 1rem = 16px (기반 단위).
pub const REM: f32 = 16.0;
/// 0.25rem = 4px (소형 최소 스텝).
pub const QR: f32 = REM / 4.0;
/// 0.5rem = 8px (중형 짝수 규격의 기본 계단).
pub const HALF: f32 = REM / 2.0;

/// 대형 치수 — **1rem(16px) 배수**로 강제. `rem(44)` = 704px.
pub const fn rem(n: i32) -> f32 {
    (n * 16) as f32
}

/// 소형 치수 — **0.25rem(4px) 배수**로 강제. `qrem(52)` = 208px.
pub const fn qrem(n: i32) -> f32 {
    (n * 4) as f32
}

/// 중형 치수 — **0.5rem(8px) 짝수 계단**으로 강제. `hrem(5)` = 40px.
/// "24·32·40·48…" 짝수 규격(비정형 짝수 금지)의 생성기.
pub const fn hrem(n: i32) -> f32 {
    (n * 8) as f32
}

/// 창/패널 같은 고정 크기를 **1rem 배수로 정규화**해 내림합니다.
/// (입력을 16px 단위로 내림해 항상 그리드에 안착 — 대형 위젯 전용.)
pub fn rem_floor(px: f32) -> f32 {
    ((px / REM) as i32) as f32 * REM
}

// ── 중형 치수 토큰: ×1.5 모듈러 스케일 (0.25rem 스냅) ──
// 기준 0.75rem(12px)에서 ×1.5씩 증가, 0.25rem 계단으로 스냅한 정거장.
// 배율: ×1.33 → ×1.5 → ×1.5 → ×1.44 → ×1.54 → ×1.5 → ×1.5 → ×1.51 (스냅 오차 범위).
// **모든 값은 rem으로 표현**한다 — px 상수를 직접 쓰지 않는다.
/// 0.75rem = 12px — 미니 컨트롤/아이콘 (S_12).
pub const S_12: f32 = 0.75 * REM;
/// 1rem = 16px — 소형 아이콘/행 높이 (S_16).
pub const S_16: f32 = 1.0 * REM;
/// 1.5rem = 24px — 소형 컨트롤 높이 (S_24).
pub const S_24: f32 = 1.5 * REM;
/// 2.25rem = 36px — 표준 버튼/입력 높이 (S_36).
pub const S_36: f32 = 2.25 * REM;
/// 3.25rem = 52px — 넉넉한 터치/대형 입력 (S_52).
pub const S_52: f32 = 3.25 * REM;
/// 5rem = 80px — 넓은 입력/미디어 썸네일 (S_80).
pub const S_80: f32 = 5.0 * REM;
/// 7.5rem = 120px — 큰 패널/미리보기 (S_120).
pub const S_120: f32 = 7.5 * REM;
/// 11.25rem = 180px — 대형 미리보기 (S_180).
pub const S_180: f32 = 11.25 * REM;
/// 17rem = 272px — 썸네일 그리드/히어로 (S_272).
pub const S_272: f32 = 17.0 * REM;
/// 25.5rem = 408px — 상한 정거장 (S_408).
pub const S_408: f32 = 25.5 * REM;
